/**
 * Otogi: Myth of Demons - Recompiled Game Entry Point
 *
 * This is the host executable that boots the recompiled game code. It performs
 * the following initialization sequence:
 *
 * 1. Load the original XBE file from disk
 * 2. Initialize the Xbox memory layout (map data sections to original VAs)
 * 3. Initialize the Xbox kernel replacement layer
 * 4. Set up game file paths for I/O redirection
 * 5. Initialize the kernel bridge (thunk table in Xbox memory)
 * 6. Initialize the stack pointer
 * 7. Build the flat dispatch table and arm the hang watchdog
 * 8. Call the game's original entry point (recompiled)
 *
 * On Windows the host also installs a VEH crash handler with dbghelp symbol
 * resolution. The POSIX path runs the same boot sequence without the Win32
 * debugging machinery.
 *
 * Boot constants and host glue only. Do not add hand-written game logic here;
 * fixes belong in config/seed_functions.json or src/game/recomp_manual.c.
 *
 * XBE Details:
 *   Title:       Otogi: Myth of Demons
 *   Entry point: 0x000E3EC7
 */

