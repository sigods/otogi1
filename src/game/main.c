/* ── POSIX host ────────────────────────────────────────────── */

int main(void)
{
    void *xbe_data = NULL;
    size_t xbe_size = 0;

    /* Unbuffered output so CRT-boot progress is observable when the process
     * dies or hangs. */
    setvbuf(stdout, NULL, _IONBF, 0);
    setvbuf(stderr, NULL, _IONBF, 0);

    fprintf(stderr, "=== Otogi: Myth of Demons - Static Recompilation ===\n");

    fprintf(stderr, "[otogi1] loading %s\n", OTOGI_XBE_PATH);
    if (!load_xbe(OTOGI_XBE_PATH, &xbe_data, &xbe_size)) {
        fprintf(stderr, "[otogi1] failed to load %s\n", OTOGI_XBE_PATH);
        return 1;
    }
    fprintf(stderr, "[otogi1] XBE loaded: %zu bytes\n", xbe_size);

    fprintf(stderr, "[otogi1] initializing Xbox memory layout\n");
    if (!xbox_MemoryLayoutInit(xbe_data, xbe_size)) {
        fprintf(stderr, "[otogi1] xbox_MemoryLayoutInit failed\n");
        free(xbe_data);
        return 1;
    }

    g_xbox_mem_offset = xbox_GetMemoryOffset();
    fprintf(stderr, "[otogi1] Xbox memory mapped. Offset: 0x%llX\n",
            (unsigned long long)g_xbox_mem_offset);

    /* Same fence and title-built KEVENT registration as the Windows host:
     * KeWaitForSingleObject on the device's own event (0x00106B6C) needs it. */
    xbox_EnableTitleEvents(1);
    xbox_Nv2aMirrorFenceEvent(0x001051C8u, 0x2Cu, 0x30u, 0x199Cu);
    fprintf(stderr, "[otogi1] NV2A fence mirror registered "
            "(device slot 0x001051C8, PUT +0x2C -> GET +0x30, "
            "title KEVENT +0x199C = 0x00106B6C)\n");

    /* Same optional APU as the Windows host: only useful alongside the
     * register traps gated on RECOMP_AC97_READY. */
    if (getenv("RECOMP_AC97_READY")) {
        g_apu_state = mcpx_apu_init_standalone((uint8_t *)xbox_GetMemoryBase());
        fprintf(stderr, "[otogi1] emulated APU %s\n",
                g_apu_state ? "up" : "FAILED to initialise");
    }

    fprintf(stderr, "[otogi1] initializing Xbox kernel replacement\n");
    xbox_kernel_init();

    fprintf(stderr, "[otogi1] setting game directory: %s\n", OTOGI_DIR);
    xbox_path_init(OTOGI_DIR, NULL);

    fprintf(stderr, "[otogi1] initializing kernel bridge\n");
    xbox_kernel_bridge_init();

    g_esp = XBOX_STACK_TOP;
    fprintf(stderr, "[otogi1] stack top: 0x%08X\n", g_esp);

    fprintf(stderr, "[otogi1] building flat dispatch table\n");
    if (!recomp_dispatch_init())
        fprintf(stderr, "[otogi1] flat dispatch unavailable; "
                        "indirect calls will use the binary search\n");

    fprintf(stderr, "[otogi1] arming watchdog\n");
    xbox_WatchdogStart();

    fprintf(stderr, "[otogi1] entry point: 0x%08X\n", OTOGI_ENTRY_POINT);
    fprintf(stderr, "[otogi1] starting game\n");
    fflush(stderr);

    xbe_entry_point();

    fprintf(stderr, "[otogi1] game returned\n");

    xbox_kernel_shutdown();
    xbox_MemoryLayoutShutdown();
    free(xbe_data);

    return 0;
}

